import { writeFileSync } from "node:fs";
import { generateSeed } from "../src/core/seed/generate";
import { buildWorkspace } from "../src/core/workspace";
import { graphToCypher } from "../src/core/graph/cypher";

const ws = buildWorkspace(generateSeed().rawEvents);
const lines = graphToCypher(ws.graph);
writeFileSync("neo4j/fixtures/seed.cypher", `// Generated by scripts/export-cypher.ts · ${ws.graph.version} · checksum ${ws.checksum}\n// Synthetic demo data.\n${lines.join("\n")}\n`);
console.log(`wrote ${lines.length} statements (checksum ${ws.checksum})`);
